"""What an MIT package installs should not be a surprise to whoever audits it.

NOTICE was thorough about frameworks and taxonomies (CWE, CAPEC, ATLAS, ASVS, PLOT4ai, ISO) and
said nothing at all about third-party *software* licences -- zero matches for lgpl, mozilla,
third-party software or dependenc. Meanwhile the documented `pip install "open-threat-model[report]"`
pulls xhtml2pdf, and xhtml2pdf pulls svglib (LGPL-3.0-or-later) and python-bidi (LGPL); certifi and
pathspec (both MPL-2.0) arrive transitively. Four non-permissive dependencies of an MIT project,
disclosed nowhere.

Nothing here is a legal conclusion and this file does not attempt one: pip installs these as
separate, independently replaceable packages, nothing is vendored, and whether that is acceptable
for a given redistribution mode is a human's call. What is mechanical -- and therefore testable --
is *disclosure*: if a copyleft package is in the graph, NOTICE has to name it.

That gap would normally be a CI licence gate over the release SBOM. It cannot be, yet: that SBOM
records zero Python components (it is generated by `trivy fs` over a tree with no `requirements.txt`
for Trivy's pip analyzer to find), so an automated licence scan of it would report nothing to
scan. This test is the stand-in until the SBOM describes the artifact.

Licence *text* is deliberately ignored when deciding: a `License` field long enough to be a licence
body rather than an SPDX expression is read from classifiers instead, so a package that merely
quotes the GPL somewhere in its own licence file is not mistaken for a GPL package.
"""

from __future__ import annotations

import re
from importlib.metadata import distributions
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[1]
_NOTICE = (_ROOT / "NOTICE").read_text(encoding="utf-8").lower()

#: Longer than this and the `License` field is the licence body, not a declaration.
_EXPRESSION_MAX_LENGTH = 60

#: Copyleft families worth disclosing. `\b`-anchored so `MPL` does not match inside another word.
_COPYLEFT = re.compile(r"\b(?:A|L)?GPL|MOZILLA PUBLIC|\bMPL[- ]|\bEUPL|\bCDDL")

#: The four measured today. Kept as a floor so the detector itself cannot silently stop working.
_KNOWN_COPYLEFT = {"certifi", "pathspec", "python-bidi", "svglib"}


def _declared_licence(metadata: object) -> str:
    """SPDX-ish expression plus classifiers; the licence body is left out on purpose."""
    get = getattr(metadata, "get")
    expression = get("License-Expression") or get("License") or ""
    if len(expression) > _EXPRESSION_MAX_LENGTH:
        expression = ""
    classifiers = getattr(metadata, "get_all")("Classifier") or []
    return f"{expression} {' '.join(classifiers)}".upper()


def _copyleft_distributions() -> dict[str, str]:
    found: dict[str, str] = {}
    for dist in distributions():
        name = dist.metadata["Name"]
        if _COPYLEFT.search(_declared_licence(dist.metadata)):
            found[name] = dist.version
    return found


def test_notice_names_every_copyleft_package_in_the_installed_graph() -> None:
    """The disclosure gap itself: a new LGPL/GPL/MPL dependency must reach NOTICE."""
    undisclosed = sorted(name for name in _copyleft_distributions() if name.lower() not in _NOTICE)
    assert undisclosed == []


@pytest.mark.parametrize("name", sorted(_KNOWN_COPYLEFT))
def test_the_detector_still_finds_the_packages_it_was_built_from(name: str) -> None:
    """Control: without this, gutting `_COPYLEFT` would make the test above pass vacuously."""
    assert name in _copyleft_distributions()


def test_notice_states_that_the_licence_question_is_not_answered_here() -> None:
    """Disclosure is the claim being made. Compatibility is explicitly a human decision."""
    assert "not a legal opinion" in _NOTICE


def test_notice_records_the_unclassifiable_npm_licence_string() -> None:
    """`rgbcolor` declares a non-SPDX string; tooling reports UNKNOWN and someone must own it."""
    assert "rgbcolor" in _NOTICE
