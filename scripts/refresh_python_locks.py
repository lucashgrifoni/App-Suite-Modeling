"""Regenerate the Python lock files used by CI, packaging, and the API image."""

import subprocess
import sys
import tomllib
from pathlib import Path
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parent.parent
PYPI = "https://pypi.org/simple"
LINUX = "x86_64-manylinux_2_39"


def main() -> None:
    with (ROOT / "pyproject.toml").open("rb") as project_file:
        backend = tomllib.load(project_file)["build-system"]["requires"]

    # CI and release run on Linux x86-64. The API image is built for multiple
    # architectures and uses only wheels, so its lock keeps platform markers.
    locks = (
        ("requirements.txt", ("pyproject.toml",), [], "3.12", ["--universal", "--extra", "api"]),
        ("requirements-build-backend.txt", ("-",), backend, "3.12", []),
        (
            "requirements-ci.txt",
            ("pyproject.toml",),
            [],
            "3.12",
            ["--extra", "dev", "--extra", "api", "--no-binary", "esprima"],
        ),
        ("requirements-pip-audit.txt", ("-",), ["pip-audit==2.10.1"], "3.12", []),
        ("requirements-release.txt", ("-",), [*backend, "build", "twine", "packaging"], "3.12", []),
        ("requirements-cli.txt", ("pyproject.toml",), [], "3.12", []),
    )
    requested = set(sys.argv[1:])
    valid_names = {name for name, *_ in locks}
    if requested - valid_names:
        raise SystemExit(f"Unknown lock files: {', '.join(sorted(requested - valid_names))}")

    with TemporaryDirectory(prefix="otm-python-locks-") as temporary:
        destination = Path(temporary)
        for name, sources, packages, python, options in locks:
            if requested and name not in requested:
                continue
            target = destination / name
            platform = [] if "--universal" in options else ["--python-platform", LINUX]
            subprocess.run(
                [
                    "uv",
                    "pip",
                    "compile",
                    *sources,
                    "--quiet",
                    "--no-config",
                    "--no-header",
                    "--python-version",
                    python,
                    *platform,
                    *options,
                    "--default-index",
                    PYPI,
                    "--exclude-newer",
                    "7 days",
                    "--generate-hashes",
                    "--only-binary",
                    ":all:",
                    "--output-file",
                    str(target),
                ],
                input="\n".join(packages),
                text=True,
                cwd=ROOT,
                check=True,
            )
        for lock_file in destination.iterdir():
            requirements = lock_file.read_text(encoding="utf-8")
            (ROOT / lock_file.name).write_text(
                "# Generated by scripts/refresh_python_locks.py from PyPI.\n" + requirements,
                encoding="utf-8",
                newline="\n",
            )


if __name__ == "__main__":
    main()
