"""
Definições do catálogo expandido (35 templates) — fonte para emitir `.otm.yaml` + `.meta.json`.

Manutenção: alterar aqui e executar `python scripts/emit_template_catalog.py`.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True)
class ExpansionTemplateSpec:
    """Um template a materializar em disco."""

    meta: dict[str, Any]
    otm: dict[str, Any]


def _base_otm(
    *,
    methodology: str,
    system_type: str,
    industry_sector: str,
    title: str,
    summary: str,
    meta_tags: list[str],
    business_desc: str,
    assumptions: list[str],
    boundaries: list[dict[str, Any]],
    components: list[dict[str, Any]],
    flows: list[dict[str, Any]],
    assets: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    return {
        "model": {
            "schema_version": "1.0.0",
            "methodology": methodology,
            "system_type": system_type,
            "industry_sector": industry_sector,
        },
        "metadata": {
            "title": title,
            "summary": summary,
            "tags": meta_tags,
        },
        "business_context": {
            "description": business_desc,
            "assumptions": assumptions,
        },
        "trust_boundaries": boundaries,
        "components": components,
        "data_flows": flows,
        "assets": assets or [],
        "threats": [],
        "mitigations": [],
        "evidence_suggestions": [],
    }


def _meta(
    *,
    id: str,
    title: str,
    description: str,
    category: str,
    category_label: str,
    tags: list[str],
    complexity: str,
    best_for: str,
    suggested_pack: str | None,
    suggested_methodology: str,
    recommendation_hints: list[str],
) -> dict[str, Any]:
    return {
        "id": id,
        "title": title,
        "description": description,
        "suggested_pack": suggested_pack,
        "category": category,
        "category_label": category_label,
        "tags": tags,
        "complexity": complexity,
        "best_for": best_for,
        "suggested_methodology": suggested_methodology,
        "recommendation_hints": recommendation_hints,
    }


def _tier2(dmz_members: list[str], app_members: list[str]) -> list[dict[str, Any]]:
    """Internet sem membros listados; DMZ com borda; aplicação com serviços internos."""
    return [
        {"id": "internet", "name": "Internet"},
        {
            "id": "dmz",
            "name": "DMZ / edge",
            "member_component_ids": dmz_members,
        },
        {
            "id": "app_tier",
            "name": "Aplicação / dados",
            "member_component_ids": app_members,
        },
    ]


def _tier1(app_members: list[str]) -> list[dict[str, Any]]:
    return [
        {"id": "internet", "name": "Internet"},
        {"id": "app_tier", "name": "Conta / VPC aplicação", "member_component_ids": app_members},
    ]


